# 8 บิตเก็บค่าได้กี่แบบ และค่าสูงสุดคือเท่าไร

bits = 8

print(2 ** bits)       # 256  ← จำนวน "แบบ" ที่เป็นไปได้
print(2 ** bits - 1)   # 255  ← ค่าสูงสุด เพราะต้องนับ 0 เป็นหนึ่งแบบด้วย

# ลองดูว่าเพิ่มบิตทีละตัว จำนวนแบบเพิ่มยังไง
for n in range(1, 9):
    print(n, 'บิต ->', 2 ** n, 'แบบ')

# 1 บิต -> 2 แบบ
# 2 บิต -> 4 แบบ
# 3 บิต -> 8 แบบ
# 4 บิต -> 16 แบบ
# 5 บิต -> 32 แบบ
# 6 บิต -> 64 แบบ
# 7 บิต -> 128 แบบ
# 8 บิต -> 256 แบบ

# Python มีเครื่องมือแปลงฐานให้ในตัว ใช้ตรวจคำตอบที่เราคิดด้วยมือได้

number = 43

print(bin(number))   # 0b101011
print(hex(number))   # 0x2b

# ตัว 0b กับ 0x ข้างหน้าคือป้ายบอกฐาน ไม่ใช่ส่วนหนึ่งของตัวเลข
# 0b101011 อ่านว่า "เลข 101011 ในฐานสอง"

# แปลงกลับก็ได้ โดยบอกฐานที่ต้องการอ่าน
print(int('101011', 2))   # 43
print(int('2b', 16))      # 43

# จำนวนเดียวกันทั้งหมด เปลี่ยนแค่วิธีเขียน

# เราตั้งใจจะหา "ค่าเฉลี่ยของ 4 กับ 10"
# ในหัวเราคิดว่า: เอาสองตัวบวกกัน แล้วหารสอง
# แต่สิ่งที่เราพิมพ์ลงไป กับสิ่งที่เราคิด ไม่ตรงกัน

first = 4
second = 10

print(first + second / 2)

# ผลลัพธ์: 9.0
# ไม่ใช่ 7.0 อย่างที่ตั้งใจ
#
# เพราะคอมพิวเตอร์อ่านคำสั่งนี้ว่า "เอา 10 หารสองก่อน แล้วค่อยบวก 4"
# ซึ่งก็คือ 4 + 5 = 9
